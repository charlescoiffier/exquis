export const THEMES = { text: TEXT_THEMES, drawing: DRAWING_THEMES } as const;

/** Un thème tiré au hasard dans la banque du type de partie. `rand` renvoie un nombre dans [0, 1[. */
export function randomTheme(type: "text" | "drawing", rand: () => number = Math.random): string {
  const bank = THEMES[type];
  return bank[Math.floor(rand() * bank.length)];
}
